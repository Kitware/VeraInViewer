"""Sample VERAin files shipped with the package.

``index.json`` and the ``previews`` images are generated by ``scripts/make_samples.py``.
"""

from __future__ import annotations

import json
from pathlib import Path

SAMPLES_DIR = Path(__file__).parent.resolve()
INDEX = SAMPLES_DIR / "index.json"


def list_samples() -> list[dict]:
    """Return ``{"name", "title", "info", "preview"}`` for each sample, ``preview`` relative to this dir."""
    if not INDEX.exists():
        return [{"name": f.name, "title": f.name, "info": [], "preview": None} for f in sample_files()]
    return json.loads(INDEX.read_text())


def sample_files() -> list[Path]:
    return sorted(SAMPLES_DIR.glob("*.xml.gold"))
